def timeline(words_per_sec: float = 2.6, gap: float = 0.5, start: float = 1.0):
    """Yield ``(start, end, text)`` with durations proportional to word count."""
    t = start
    for s in SENTENCES:
        d = max(len(s.split()) / words_per_sec, 1.5)
        yield t, t + d, s
        t += d + gap


def total_duration() -> float:
    return list(timeline())[-1][1] + 1.0


def make_srt() -> str:
    from cliparab_core.subtitles import to_srt

    return to_srt(list(timeline()))
